const MISSING_GLYPH: [u8; 8] = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x1f, 0x00, 0x00];

#[derive(Clone, Copy)]
struct CachedGlyph {
    metrics: fontdue::Metrics,
}

pub struct TextRenderer {
    font: Option<Font>,
    glyphs: HashMap<(u32, u32), CachedGlyph>,
    rasterized: HashMap<(u32, u32), Vec<u8>>,
    source: String,
}

impl TextRenderer {
    pub fn new() -> Self {
        let path = std::env::var_os("NXVIEW_UI_FONT")
            .map(PathBuf::from)
            .or_else(default_font_path);
        let mut source = String::from("embedded ASCII 8x8");
        let font = path.and_then(|path| {
            let bytes = std::fs::read(&path).ok()?;
            let font = Font::from_bytes(
                bytes,
                FontSettings {
                    collection_index: 0,
                    scale: 40.0,
                    load_substitutions: false,
                },
            )
            .ok()?;
            source = path.display().to_string();
            Some(font)
        });
        Self {
            font,
            glyphs: HashMap::new(),
            rasterized: HashMap::new(),
            source,
        }
    }

    pub fn source(&self) -> &str {
        &self.source
    }

    pub fn has_cjk_font(&self) -> bool {
        self.font.as_ref().is_some_and(|font| font.has_glyph('文'))
    }

    fn ascent(&self, px: f32) -> f32 {
        self.font
            .as_ref()
            .and_then(|font| font.horizontal_line_metrics(px))
            .map_or(px * 0.82, |metrics| metrics.ascent)
    }

    pub fn text_width(&self, text: &str, px: f32) -> i32 {
        if let Some(font) = &self.font {
            let width: f32 = text
                .chars()
                .map(|ch| {
                    if font.has_glyph(ch) {
                        font.metrics(ch, px).advance_width
                    } else {
                        px * 0.55
                    }
                })
                .sum();
            return width.round() as i32;
        }
        let scale = if px >= 13.0 { 2 } else { 1 };
        text.chars().count() as i32 * 6 * scale
    }

    #[allow(clippy::too_many_arguments)]
    pub fn draw(
        &mut self,
        canvas: &mut Canvas,
        text: &str,
        x: i32,
        y: i32,
        px: f32,
        color: u32,
        clip: Rect,
    ) {
        if text.is_empty() || px <= 0.0 {
            return;
        }
        if self.font.is_some() {
            self.draw_font(canvas, text, x, y, px, color, clip);
        } else {
            self.draw_bitmap(canvas, text, x, y, px, color, clip);
        }
    }

    pub fn draw_centered(
        &mut self,
        canvas: &mut Canvas,
        text: &str,
        rect: Rect,
        px: f32,
        color: u32,
    ) {
        let width = self.text_width(text, px);
        let x = rect.x + (rect.w - width) / 2;
        let y = rect.y + (rect.h - px as i32) / 2 - 1;
        let clip = rect.intersect(Rect::new(0, 0, canvas.width as i32, canvas.height as i32));
        self.draw(canvas, text, x, y, px, color, clip);
    }

    #[allow(clippy::too_many_arguments)]
    fn draw_font(
        &mut self,
        canvas: &mut Canvas,
        text: &str,
        x: i32,
        y: i32,
        px: f32,
        color: u32,
        clip: Rect,
    ) {
        let baseline = y + self.ascent(px).round() as i32;
        let mut pen = x;
        for ch in text.chars() {
            if pen >= clip.right() {
                break;
            }
            if ch == '\n' {
                continue;
            }
            let key = (ch as u32, px.to_bits());
            let has_glyph = self.font.as_ref().is_some_and(|font| font.has_glyph(ch));
            if !has_glyph {
                self.draw_missing(canvas, pen, y, px, color, clip);
                pen += (px * 0.55).round() as i32;
                continue;
            }
            if !self.glyphs.contains_key(&key) {
                let (metrics, bitmap) = self.font.as_ref().expect("font checked").rasterize(ch, px);
                self.glyphs.insert(key, CachedGlyph { metrics });
                self.rasterized.insert(key, bitmap);
            }
            let glyph = self.glyphs[&key];
            let bitmap = &self.rasterized[&key];
            let gx = pen + glyph.metrics.xmin;
            let gy = baseline - glyph.metrics.ymin - glyph.metrics.height as i32;
            let width = glyph.metrics.width;
            let height = glyph.metrics.height;
            for row in 0..height {
                for column in 0..width {
                    let coverage = bitmap[row * width + column];
                    if coverage == 0 {
                        continue;
                    }
                    let px_x = gx + column as i32;
                    let px_y = gy + row as i32;
                    if clip.contains(px_x, px_y) {
                        canvas.blend(px_x, px_y, color, coverage);
                    }
                }
            }
            pen += glyph.metrics.advance_width.round() as i32;
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn draw_bitmap(
        &self,
        canvas: &mut Canvas,
        text: &str,
        x: i32,
        y: i32,
        px: f32,
        color: u32,
        clip: Rect,
    ) {
        let scale = if px >= 13.0 { 2 } else { 1 };
        let cell_width = 6 * scale;
        let cell_height = 8 * scale;
        let top = y + ((px as i32 - cell_height) / 2).max(0);
        let mut pen = x;
        for ch in text.chars() {
            if pen >= clip.right() {
                break;
            }
            if ch == '\n' {
                continue;
            }
            let code = ch as u32;
            let rows = if (0x20..0x7f).contains(&code) {
                &ASCII_8X8[(code - 0x20) as usize]
            } else {
                &MISSING_GLYPH
            };
            for (row, bits) in rows.iter().enumerate() {
                for column in 0..8 {
                    if bits & (1 << column) == 0 {
                        continue;
                    }
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px_x = pen + column * scale + sx;
                            let px_y = top + row as i32 * scale + sy;
                            if clip.contains(px_x, px_y) {
                                canvas.put(px_x, px_y, color);
                            }
                        }
                    }
                }
            }
            pen += cell_width;
        }
    }

    fn draw_missing(&self, canvas: &mut Canvas, pen: i32, y: i32, px: f32, color: u32, clip: Rect) {
        let size = (px.round() as i32).max(3);
        let top = y + ((px as i32 - size) / 2).max(0);
        let dim = blend_color(color, 0x00202830, 0.5);
        for x in 0..size {
            for width in [0, 1] {
                let px_x = pen + x;
                let px_y = top + width * (size - 1);
                if clip.contains(px_x, px_y) {
                    canvas.put(px_x, px_y, dim);
                }
            }
        }
        for yy in 0..size {
            for column in [0, 1] {
                let px_x = pen + column * (size - 1);
                let px_y = top + yy;
                if clip.contains(px_x, px_y) {
                    canvas.put(px_x, px_y, dim);
                }
            }
        }
    }
}

fn default_font_path() -> Option<PathBuf> {
    #[cfg(windows)]
    {
        let path = PathBuf::from(DEFAULT_FONT);
        if path.is_file() {
            return Some(path);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bitmap_table_covers_printable_ascii() {
        assert_eq!(ASCII_8X8.len(), 0x7f - 0x20);
        assert_ne!(ASCII_8X8[('A' as usize) - 0x20], [0; 8]);
        assert_ne!(ASCII_8X8[('0' as usize) - 0x20], [0; 8]);
        assert_eq!(ASCII_8X8[0], [0; 8]);
    }

    #[test]
    fn fallback_width_uses_fixed_cells() {
        let renderer = TextRenderer {
            font: None,
            glyphs: HashMap::new(),
            rasterized: HashMap::new(),
            source: String::from("test"),
        };
        assert_eq!(renderer.text_width("abc", 10.0), 18);
        assert_eq!(renderer.text_width("abc", 14.0), 36);
        assert_eq!(renderer.text_width("", 10.0), 0);
    }
}
